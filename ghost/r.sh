#!/usr/bin/env bash
# r.sh - run one command as uid 0 on the TV and bring its output back.
#
# The vendor's TvService (transaction 4400) can start a script as root, but that is
# fire-and-forget: it execs, and whatever the script prints goes nowhere. This wraps
# it into a usable one-shot command channel:
#
#   ./r.sh 'id'
#   ./r.sh -t 60 'dmesg | tail -50'
#
# Mechanics, in order:
#   1. inner script  : written locally, pushed to /sdcard/Download/.r_inner.sh
#   2. cmd.sh        : detached copier that moves the inner script onto /data (ext4,
#                      executable) and runs it in the background. It must detach: the
#                      agent runs cmd.sh through a synchronous init exec, so a blocking
#                      cmd.sh would stall init.
#   3. result        : inner script writes "/data/anr/.r.out", first line a nonce, last
#                      line R_EXIT=<code>. Only the same run's nonce is accepted, so a
#                      stale file from a previous command can never be mistaken for this
#                      one's output.
#
# Requires the root agent to be up (bash ghost/ensure_root.sh).
#
# Environment: ADB (path to adb), DEV (host:port), R_TIMEOUT (seconds).
set -u

ADB="${ADB:-/d/AI/DeepSeek-Harness/K90Ultra/_fbtools/adb.exe}"
DEV="${DEV:-192.168.31.243:5555}"
TIMEOUT="${R_TIMEOUT:-20}"

HERE="$(cd "$(dirname "$0")" && pwd -W 2>/dev/null || pwd)"

while [ $# -gt 0 ]; do
  case "$1" in
    -t) TIMEOUT="$2"; shift 2 ;;
    -s) DEV="$2"; shift 2 ;;
    --) shift; break ;;
    *)  break ;;
  esac
done
CMD="${*:-}"
[ -n "$CMD" ] || { echo "usage: r.sh [-t seconds] [-s host:port] 'command'" >&2; exit 2; }

NONCE="$(date +%s)-$$"
INNER="$HERE/.r_inner.sh"
LAUNCH="$HERE/.r_cmd.sh"

# The command is inserted with printf '%s', so nothing in it is expanded here.
{
  echo '#!/system/bin/sh'
  echo '# generated by r.sh - do not edit'
  echo 'export PATH=/system/bin:/vendor/bin:/vendor/xbin'
  echo "echo R_NONCE=$NONCE > /data/anr/.r.out"
  echo '{'
  printf '%s\n' "$CMD"
  echo '} >> /data/anr/.r.out 2>&1'
  echo 'echo "R_EXIT=$?" >> /data/anr/.r.out'
} > "$INNER"

cat > "$LAUNCH" <<EOF
( cp /sdcard/Download/.r_inner.sh /data/anr/.r_inner.sh
  chmod 0755 /data/anr/.r_inner.sh
  /system/bin/sh /data/anr/.r_inner.sh
) </dev/null >/dev/null 2>&1 &
EOF

# Remote paths carry a leading double slash: MSYS rewrites POSIX-looking arguments
# before adb.exe sees them, and '//sdcard' survives that rewrite as '/sdcard'.
MSYS2_ARG_CONV_EXCL='*' MSYS_NO_PATHCONV=1 "$ADB" -s "$DEV" push "$INNER" //sdcard/Download/.r_inner.sh >/dev/null 2>&1 || {
  echo "r.sh: push of inner script failed (is adb connected?)" >&2; exit 1; }
MSYS2_ARG_CONV_EXCL='*' MSYS_NO_PATHCONV=1 "$ADB" -s "$DEV" push "$LAUNCH" //sdcard/Download/cmd.sh >/dev/null 2>&1 || {
  echo "r.sh: push of cmd.sh failed" >&2; exit 1; }

# Wait for this run to finish, not merely to start: the nonce is written before the
# command runs, so waiting on it alone would return half the output of a slow command.
# The trailing R_EXIT= line is what marks completion.
waited=0
done=0
while [ "$waited" -lt "$TIMEOUT" ]; do
  sleep 1
  waited=$((waited + 1))
  OUT="$(MSYS2_ARG_CONV_EXCL='*' MSYS_NO_PATHCONV=1 "$ADB" -s "$DEV" exec-out cat /data/anr/.r.out 2>/dev/null | tr -d '\r')"
  case "$OUT" in
    "R_NONCE=$NONCE"*R_EXIT=*) done=1; break ;;
  esac
done

if [ "$done" != 1 ]; then
  echo "r.sh: no result after ${TIMEOUT}s (raise it with -t). Is the root agent running? (bash ghost/ensure_root.sh)" >&2
  exit 1
fi

RC="$(printf '%s\n' "$OUT" | sed -n 's/^R_EXIT=\([0-9]*\)$/\1/p' | tail -n 1)"
printf '%s\n' "$OUT" | sed '1d;$d'
rm -f "$INNER" "$LAUNCH"
exit "${RC:-0}"
